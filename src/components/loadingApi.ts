export function resolveLoadingApiLocale(locale: string): LoadingApiLocale {
  const language = locale.trim().replace(/_/g, '-').toLowerCase().split('-')[0];
  if (language === 'zh') return 'zh-CN';
  if (language === 'ja' || language === 'ko' || language === 'fr') return language;
  return 'en';
}

function localizedRows(entries: readonly LoadingApiEntry[], locale: LoadingApiLocale): ApiRow[] {
  const copy = loadingApiCopy[locale];
  return entries.map(entry => [
    entry.required ? `${entry.name} *` : entry.name,
    entry.type,
    entry.defaultValue,
    copy[entry.descriptionKey],
    copy[entry.descriptionKey],
  ] as const);
}

/** Ready for `<ApiGroups component="loading" groups={getLoadingApiGroups(locale)} />`. */
export function getLoadingApiGroups(locale: string): ApiGroup[] {
  const resolved = resolveLoadingApiLocale(locale);
  return [
    { id: 'loading', title: 'Loading', rows: localizedRows(loadingApi, resolved) },
    { id: 'loading-stage', title: 'LoadingStage', rows: localizedRows(loadingStageApi, resolved) },
    { id: 'loading-labels', title: 'LoadingLabels', rows: localizedRows(loadingLabelsApi, resolved) },
  ];
}

