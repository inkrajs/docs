import assert from 'node:assert/strict';

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch();
const errors = [];
try {
  for (const width of [1305, 390]) {
    const page = await browser.newPage({ viewport: { width, height: 954 } });
    await page.routeWebSocket('**/*', socket => socket.close());
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('http://127.0.0.1:4180/components/select#preview');
    const fixturePath = new URL('./fixtures/multi-select.tsx', import.meta.url).pathname;
    await page.evaluate(async path => (await import(`/@fs${path}`)).mountMultiSelectFixture(), fixturePath);
    const trigger = name => page.getByRole('combobox', { name, exact: true });
    const read = () => page.locator('#multi-form').evaluate(form => Object.fromEntries(['cities', 'readonly', 'disabled', 'required'].map(name => [name, new FormData(form).getAll(name)])));
    await trigger('Uncontrolled').waitFor();
    assert.equal(await trigger('Uncontrolled').innerText(), 'Auckland');
    assert.deepEqual((await read()).cities, ['akl']);
    await trigger('Uncontrolled').click();
    await page.getByRole('option', { name: 'Wellington', exact: true }).click();
    assert.equal(await trigger('Uncontrolled').getAttribute('aria-expanded'), 'true', 'selection stays open');
    assert.equal(await page.getByRole('listbox').getAttribute('aria-multiselectable'), 'true');
    assert.deepEqual((await read()).cities, ['akl', 'wlg']);
    await page.getByRole('option', { name: 'Auckland', exact: true }).click();
    assert.deepEqual((await read()).cities, ['wlg'], 'selected option removes itself');
    assert.equal(await page.getByRole('option', { name: 'Christchurch', exact: true }).getAttribute('aria-disabled'), 'true');
    await page.keyboard.press('Escape');
    await page.waitForFunction(node => document.activeElement === node, await trigger('Uncontrolled').elementHandle());
    assert(await trigger('Uncontrolled').evaluate(node => document.activeElement === node));
    await page.getByRole('button', { name: 'Clear Uncontrolled', exact: true }).click();
    assert.deepEqual((await read()).cities, []);
    assert.equal(await trigger('Uncontrolled').innerText(), 'Choose cities');
    await page.getByRole('button', { name: 'Read cities', exact: true }).click();
    await page.getByRole('button', { name: 'Reset cities', exact: true }).click();
    await page.waitForFunction(() => new FormData(document.getElementById('multi-form')).get('cities') === 'akl');
    await page.getByRole('button', { name: 'Clear Uncontrolled', exact: true }).click();
    await page.getByRole('button', { name: 'Prevent reset', exact: true }).click();
    await page.getByRole('button', { name: 'Reset cities', exact: true }).click();
    await page.waitForTimeout(50);
    assert.deepEqual((await read()).cities, [], 'prevented reset stays unchanged');
    await trigger('Controlled').click();
    await page.getByRole('option', { name: 'Queenstown', exact: true }).click();
    assert.deepEqual(JSON.parse(await page.getByTestId('multi-values').textContent()), ['wlg', 'zqn']);
    await page.getByRole('button', { name: 'Clear popup Controlled', exact: true }).click();
    assert.deepEqual(JSON.parse(await page.getByTestId('multi-values').textContent()), []);
    await page.keyboard.press('Escape');
    await page.waitForTimeout(250);
    await page.getByRole('button', { name: 'Clear Held controlled', exact: true }).click();
    assert.equal(await trigger('Held controlled').innerText(), 'Auckland', 'controlled consumer owns value');
    assert.equal(await trigger('Readonly').getAttribute('aria-readonly'), 'true');
    assert.equal(await page.getByRole('button', { name: 'Clear Readonly', exact: true }).isDisabled(), true);
    await trigger('Readonly').click();
    assert.equal(await trigger('Readonly').getAttribute('aria-expanded'), 'false');
    assert.equal(await trigger('Disabled').isDisabled(), true);
    assert.deepEqual((await read()).disabled, []);
    assert.deepEqual((await read()).readonly, ['akl'], 'external form association');
    assert.equal(await trigger('Required').getAttribute('aria-required'), 'true');
    assert.equal(await trigger('Required').getAttribute('aria-invalid'), 'true');
    assert(await trigger('Required').getAttribute('aria-describedby'));
    assert.equal(await page.locator('#multi-form').evaluate(form => form.checkValidity()), false);
    await trigger('Required').click();
    await page.getByRole('option', { name: 'Auckland', exact: true }).click();
    await page.keyboard.press('Escape');
    await page.waitForTimeout(250);
    assert.equal(await page.locator('#multi-form').evaluate(form => form.checkValidity()), true);
    await trigger('Controlled').focus();
    await page.keyboard.press('ArrowDown');
    await page.keyboard.press('End');
    await page.keyboard.press('Enter');
    assert(JSON.parse(await page.getByTestId('multi-values').textContent()).includes('dud'));
    assert.equal(await trigger('Controlled').getAttribute('aria-expanded'), 'true');
    await page.keyboard.press('Escape');
    await page.waitForTimeout(250);
    await trigger('RTL').click();
    assert.equal(await page.getByRole('listbox').evaluate(node => getComputedStyle(node).direction), 'rtl');
    await page.keyboard.press('Escape');
    await page.waitForTimeout(250);
    await trigger('Single compatibility').click();
    await page.getByRole('option', { name: 'Queenstown', exact: true }).click();
    assert.equal(await trigger('Single compatibility').getAttribute('aria-expanded'), 'false');
    assert.equal(await trigger('Single compatibility').innerText(), 'Queenstown');
    await trigger('Single readonly').focus();
    await page.keyboard.press('q');
    await page.keyboard.press('ArrowDown');
    assert.equal(await trigger('Single readonly').getAttribute('aria-expanded'), 'false');
    assert.equal(await trigger('Single readonly').innerText(), 'Auckland');
    assert.equal(await page.locator('#multi-form').evaluate(form => new FormData(form).get('singleReadonly')), 'akl');
    await trigger('Protected').click();
    await page.keyboard.press('Escape');
    await page.waitForTimeout(250);
    assert.equal(await trigger('Protected').getAttribute('aria-expanded'), 'true', 'Escape dismissal can be canceled');
    await page.mouse.click(width - 4, 4);
    await page.waitForTimeout(250);
    assert.equal(await trigger('Protected').getAttribute('aria-expanded'), 'true', 'outside dismissal can be canceled');
    await page.getByRole('button', { name: 'Close protected', exact: true }).click();
    await page.waitForTimeout(250);
    for (const theme of ['light', 'dark']) {
      await page.evaluate(theme => {
        document.documentElement.dataset.theme = theme;
        document.documentElement.dataset.inkraTheme = theme;
      }, theme);
      await trigger('Controlled').click();
      await page.waitForTimeout(500);
      const box = await page.getByRole('listbox').boundingBox();
      assert(box.width > 50 && box.height > 44);
      assert(box.x >= 0 && box.x + box.width <= width + 1);
      await page.screenshot({ path: `/tmp/inkra-multi-select-${width}-${theme}.png`, fullPage: true });
      await page.keyboard.press('Escape');
      await page.waitForTimeout(250);
    }
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.close();
    console.log(`PASS multi-select selection, forms, reset, readonly, keyboard, RTL, themes and single compatibility at ${width}px`);
  }
  assert.deepEqual(errors, []);
} finally {
  await browser.close();
}
