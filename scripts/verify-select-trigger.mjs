import assert from 'node:assert/strict';

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch();
const errors = [];
try {
  for (const width of [1305, 390]) {
    const page = await browser.newPage({ viewport: { width, height: 954 } });
    page.setDefaultTimeout(15000);
    page.on('pageerror', error => errors.push(error.message));
    await page.goto((process.env.INKRA_DOCS_URL || 'http://127.0.0.1:4180') + '/components/select#preview');
    const playground = page.locator('.component-playground').first();
    const controls = playground.locator('.preview-controls');
    const trigger = playground.locator('.preview-stage .inkra-select__trigger');
    const category = label => controls.getByRole('tab', { name: label, exact: true });
    const toggle = label => controls.getByRole('switch', { name: label, exact: true }).click();
    for (const [label, size, height] of [['Small', 24, 36], ['Medium', 28, 44], ['Large', 32, 48]]) {
      await controls.getByRole('combobox', { name: '尺寸', exact: true }).click();
      await page.getByRole('option', { name: label, exact: true }).click();
      const glyph = await trigger.locator('.inkra-select__trigger-glyph').boundingBox();
      const slot = await trigger.locator('.inkra-select__trigger-icon').boundingBox();
      const surface = await trigger.locator('.inkra-select__trigger-surface').boundingBox();
      assert.equal(glyph.width, size, `${label} arrow canvas`);
      assert.equal(glyph.height, size, `${label} arrow canvas height`);
      assert.equal(slot.width, size, `${label} arrow slot`);
      assert.equal(surface.height, height, `${label} control height unchanged`);
    }
    await controls.getByRole('combobox', { name: '尺寸', exact: true }).click();
    await page.getByRole('option', { name: 'Medium', exact: true }).click();
    await page.getByRole('listbox').waitFor({ state: 'hidden' });
    await page.waitForTimeout(250);
    await page.screenshot({ path: `/tmp/inkra-select-chevron-${width}.png` });
    await category('内容').click();
    await toggle('前置图标');
    await toggle('后置图标');
    assert.equal(await trigger.locator('.inkra-select__trigger-slot').count(), 2);
    await toggle('隐藏下拉箭头');
    assert.equal(await trigger.locator('.inkra-select__trigger-icon').count(), 0);
    await trigger.click();
    await page.getByRole('option', { name: '团队', exact: true }).click();
    assert.match(await trigger.textContent(), /团队/);
    await toggle('纯图标触发器');
    assert.equal(await trigger.locator('.inkra-select__trigger-slot').count(), 1);
    const box = await trigger.boundingBox();
    assert(box.width >= 44 && Math.abs(box.width - box.height) < 1, 'square hit target');
    const hiddenValue = trigger.locator('.inkra-select__trigger-value-hidden');
    const valueId = await hiddenValue.getAttribute('id');
    assert((await trigger.getAttribute('aria-describedby')).split(' ').includes(valueId));
    assert.match(await hiddenValue.textContent(), /团队/);
    assert.equal(await trigger.getAttribute('aria-label'), '可见范围');
    await trigger.focus();
    await page.keyboard.press('ArrowDown');
    await page.getByRole('listbox').waitFor();
    assert(await page.getByRole('listbox').evaluate(node => node.clientWidth >= 190), 'popup readable with tiny trigger');
    await page.keyboard.press('Escape');
    await page.getByRole('listbox').waitFor({ state: 'hidden' });
    assert(await trigger.evaluate(node => node === document.activeElement), 'Escape restores focus');
    await playground.getByRole('button', { name: '读取表单', exact: true }).click();
    assert.match(await playground.locator('.component-demo-status').textContent(), /team/);
    await playground.getByRole('button', { name: '重置', exact: true }).click();
    assert.match(await hiddenValue.textContent(), /请选择/);
    await category('基础').click();
    await toggle('多选');
    await trigger.click();
    await page.getByRole('option', { name: '仅自己', exact: true }).click();
    await page.getByRole('option', { name: '团队', exact: true }).click();
    assert(await page.getByRole('listbox').isVisible(), 'multiple stays open');
    await page.keyboard.press('Escape');
    await page.getByRole('listbox').waitFor({ state: 'hidden' });
    assert.match(await hiddenValue.textContent(), /仅自己.*团队/);
    await playground.getByRole('button', { name: '读取表单', exact: true }).click();
    assert.match(await playground.locator('.component-demo-status').textContent(), /private.*team/);
    await category('状态').click();
    await toggle('只读');
    await trigger.click();
    assert.equal(await page.getByRole('listbox').count(), 0, 'readonly stays closed');
    await toggle('只读');
    await toggle('禁用');
    assert(await trigger.isDisabled());
    await toggle('禁用');
    await category('内容').click();
    await toggle('纯图标触发器');
    await category('布局').click();
    await controls.getByRole('combobox', { name: '阅读方向', exact: true }).click();
    await page.getByRole('option', { name: 'RTL', exact: true }).click();
    const slots = await trigger.locator('.inkra-select__trigger-slot').all();
    assert((await slots[0].boundingBox()).x > (await slots[1].boundingBox()).x, 'logical icon slots follow RTL');
    await category('内容').click();
    await toggle('撑满宽度');
    assert.equal(await trigger.getAttribute('data-full-width'), 'false');
    await playground.getByRole('tab', { name: '代码', exact: true }).click();
    const code = await playground.locator('code').textContent();
    for (const prop of ['startIcon=', 'endIcon=', 'hideIndicator={true}', 'fullWidth={false}', 'dir="rtl"']) assert(code.includes(prop));
    await playground.getByRole('tab', { name: '预览', exact: true }).click();
    const example = page.locator('.component-example').filter({ has: page.getByRole('heading', { name: '纯图标触发器', exact: true }) });
    const iconTrigger = example.getByRole('combobox');
    await iconTrigger.scrollIntoViewIfNeeded();
    await iconTrigger.click();
    await page.getByRole('option', { name: 'English', exact: true }).click();
    await page.getByRole('listbox').waitFor({ state: 'hidden' });
    assert.match(await iconTrigger.locator('.inkra-select__trigger-value-hidden').textContent(), /English/);
    await page.waitForFunction(() => {
      const canvas = document.querySelector('.component-example [data-icon-only="true"] .inkra-select__trigger-slot canvas');
      if (!canvas?.width) return false;
      return canvas.getContext('2d').getImageData(0, 0, canvas.width, canvas.height).data.some((value, index) => index % 4 === 3 && value > 20);
    });
    await example.screenshot({ path: `/tmp/inkra-select-icon-trigger-${width}.png` });
    await page.evaluate(() => window.scrollTo(0, 0));
    if (width < 768) await page.getByRole('button', { name: '打开文档目录', exact: true }).click();
    const language = page.locator(`${width < 768 ? '.mobile-drawer' : '.desktop-sidebar'} .language-control`);
    const languageTrigger = language.getByRole('combobox');
    assert.equal(await language.locator(':scope > .docs-pencil-icon').count(), 0);
    assert.equal(await languageTrigger.locator('.inkra-select__trigger-slot canvas').count(), 1);
    await languageTrigger.locator('.inkra-select__trigger-slot').click();
    await page.getByRole('option', { name: 'English', exact: true }).click();
    await page.getByRole('listbox').waitFor({ state: 'hidden' });
    assert.match(await languageTrigger.textContent(), /English/);
    await languageTrigger.click();
    await page.getByRole('option', { name: '中文', exact: true }).click();
    await page.getByRole('listbox').waitFor({ state: 'hidden' });
    await languageTrigger.focus();
    await language.screenshot({ path: `/tmp/inkra-select-language-${width}.png` });
    if (width < 768) {
      await page.keyboard.press('Escape');
      await page.locator('.mobile-drawer').waitFor({ state: 'hidden' });
    }
    await page.mouse.move(0, 0);
    await page.waitForTimeout(250);
    await page.screenshot({ path: `/tmp/inkra-select-trigger-${width}.png` });
    if (width > 768) {
      await page.getByRole('radio', { name: '深色主题', exact: true }).check();
      await iconTrigger.scrollIntoViewIfNeeded();
      await iconTrigger.focus();
      await page.keyboard.press('Tab');
      await page.keyboard.press('Shift+Tab');
      assert(await iconTrigger.evaluate(node => node.matches(':focus-visible')), 'icon-only keyboard focus');
      await page.waitForTimeout(500);
      await example.screenshot({ path: '/tmp/inkra-select-icon-trigger-dark.png' });
      await iconTrigger.press('ArrowDown');
      await page.getByRole('option', { name: '中文', exact: true }).click();
      await page.getByRole('listbox').waitFor({ state: 'hidden' });
    }
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'no page overflow');
    console.log(`PASS ${width}px: trigger slots, hiding, icon-only, form/reset, single/multiple, readonly/disabled, RTL, source, language selector`);
    await page.close();
  }
  assert.deepEqual(errors, []);
} finally {
  await browser.close();
}
